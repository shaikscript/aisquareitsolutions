function h(?string $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function connect_mysql(string $host, int $port, string $name, string $user, string $password): PDO
{
    return new PDO(
        sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $host, $port, $name),
        $user,
        $password,
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_TIMEOUT => 10]
    );
}

function run_schema(PDO $pdo, string $schemaFile): int
{
    $sql = (string) file_get_contents($schemaFile);
    $lines = preg_split('/\R/', $sql) ?: [];
    $clean = [];
    foreach ($lines as $line) {
        if (preg_match('/^\s*--/', $line)) {
            continue;
        }
        $clean[] = $line;
    }
    $statements = preg_split('/;\s*\n/', implode("\n", $clean)) ?: [];
    $executed = 0;
    foreach ($statements as $statement) {
        $statement = trim($statement);
        if ($statement === '') {
            continue;
        }
        try {
            $pdo->exec($statement);
            $executed++;
        } catch (PDOException $error) {
            $message = $error->getMessage();
            if (stripos($message, 'already exists') !== false || stripos($message, 'Duplicate key name') !== false) {
                continue;
            }
            throw $error;
        }
    }
    return $executed;
}

