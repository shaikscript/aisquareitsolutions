<?php
/**
 * SPA shell.
 *
 * Serves the single-file build and tells the frontend which folder it lives in,
 * so the same upload works at a domain root or inside /subfolder/.
 */

declare(strict_types=1);

$shell = __DIR__ . '/app.html';
if (!is_file($shell)) {
    http_response_code(503);
    header('Content-Type: text/html; charset=utf-8');
    echo '<!doctype html><meta charset="utf-8"><title>AI Square · setup</title>'
        . '<div style="font-family:system-ui;max-width:560px;margin:12vh auto;padding:0 24px;line-height:1.6">'
        . '<h1 style="font-size:1.4rem">The site shell is missing</h1>'
        . '<p>Upload <code>app.html</code> next to this file (it is generated by <code>npm run build</code>).</p>'
        . '<p>Then open <a href="install.php">install.php</a> to finish the database setup.</p></div>';
    exit;
}

$dir = str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/index.php'));
$base = rtrim($dir === '/' || $dir === '.' ? '' : $dir, '/');
$baseUrl = $base === '' ? '/' : $base . '/';

$html = file_get_contents($shell);
$injection = '<base href="' . htmlspecialchars($baseUrl, ENT_QUOTES) . '">'
    . '<script>window.__AISQUARE_BASE__=' . json_encode($base, JSON_UNESCAPED_SLASHES) . ';</script>';
$html = preg_replace('/<head>/i', '<head>' . $injection, $html, 1);

header('Content-Type: text/html; charset=utf-8');
header('Cache-Control: no-store, must-revalidate');
header('X-Content-Type-Options: nosniff');
header('Referrer-Policy: strict-origin-when-cross-origin');
echo $html;
